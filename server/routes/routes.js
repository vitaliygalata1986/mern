import express from 'express';
// Этот импорт пока не используется: проверки идентификаторов ещё не добавлены.
import mongoose from 'mongoose';
import Posts from '../models/Posts.js';

// Router() создаёт отдельный маршрутизатор, который подключается в index.js.
const router = express.Router();

// Заглушка списка: чтение сообщений из MongoDB пока не реализовано.
router.get('/', (req, res) => {
  // req — входящий запрос, res — объект для отправки ответа.
  res.send({ messages: 'Get all messages' });
});

// Заглушка одного сообщения: req.params.id пока не используется.
router.get('/:id', (req, res) => {
  res.send({ messages: 'Get one messages' });
});

router.post('/', async (req, res) => {
  // Берём поля из JSON-тела, разобранного express.json() в index.js.
  const { text, author } = req.body;
  try {
    // Проверяем данные по схеме Posts и ждём сохранения документа в MongoDB.
    const post = await Posts.create({
      text,
      author,
    });
    // Возвращаем сохранённый документ, включая _id и временные метки.
    res.status(200).json(post);
  } catch (error) {
    // Сейчас любая ошибка внутри try возвращается клиенту со статусом 400.
    res.status(400).send({ error: error.message });
  }
});

// Заглушка обновления: документ в базе не изменяется.
router.patch('/:id', (req, res) => {
  res.send({ messages: 'UPDATE one message' });
});

// Заглушка удаления: документ в базе не удаляется.
router.delete('/:id', (req, res) => {
  res.send({ messages: 'DELETE one message' });
});

export default router;

