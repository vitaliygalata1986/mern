import mongoose from 'mongoose';

// Schema описывает поля документа и правила их проверки перед сохранением.
const { Schema } = mongoose;

const postaSchema = new Schema(
  {
    text: {
      type: String,
      required: true,
    },
    author: {
      type: String,
      required: true,
    },
  },
  {
    timestamps: true, // автоматически добавляет поля createdAt и updatedAt
  },
);

// 'Posts' — имя модели в Mongoose, 'posts' — явно заданное имя коллекции MongoDB.
export default mongoose.model('Posts', postaSchema, 'posts');

/*
Подробное объяснение PostsModel.js

Этот файл описывает структуру сообщений и экспортирует модель для работы
с коллекцией posts. Подключение к MongoDB выполняется отдельно, в index.js.

1. const { Schema } = mongoose
   Достаём конструктор Schema из объекта mongoose с помощью деструктуризации.
   Это позволяет писать new Schema(...) вместо new mongoose.Schema(...).

2. const postaSchema = new Schema(...)
   Создаём схему. Первый объект содержит поля документа, второй — настройки.
   Имя переменной postaSchema используется только в коде и не задаёт имя
   коллекции или поля в базе.

3. text и author
   text хранит текст сообщения, author — автора. Оба поля имеют тип String
   и required: true: перед сохранением Mongoose проверяет их обязательность.
   Отсутствующее значение, null или пустая строка не проходят эту проверку.
   При этом пробелы автоматически не обрезаются, ограничений длины нет.
   Mongoose может приводить значения к строке, поэтому type: String
   не означает строгую проверку исходного типа данных в HTTP-запросе.

4. timestamps: true
   Mongoose автоматически добавляет createdAt (время создания) и updatedAt
   (время последнего обновления). В JSON-ответе даты представлены строками.
   Также документ по умолчанию получает _id типа ObjectId и поле версии __v.
   Поле __v служебное: это не счётчик всех изменений сообщения.

5. mongoose.model('Posts', postaSchema, 'posts')
   Создаём модель Posts по схеме postaSchema. Третий аргумент явно указывает
   коллекцию posts, чтобы её имя не зависело от автоматического преобразования.
   Схема описывает данные, а модель предоставляет методы работы с ними.
   Само объявление модели не создаёт сообщение: в PostsControllers.js для этого
   вызывается Posts.create({ text, author }), который проверяет и сохраняет
   документ. Ошибка проверки попадает в catch POST-обработчика.

6. export default
   Экспортируем модель по умолчанию. В controllers/PostsControllers.js
   она импортируется как Posts и используется во всех CRUD-операциях:
   create — создание, find — список, findById — поиск одного документа,
   findByIdAndDelete — удаление, findByIdAndUpdate — обновление.
   Для обновления контроллер включает runValidators: true. Эти проверки
   применяются к обновляемым полям и поддерживаемым операциям обновления;
   это не полная повторная проверка всего документа, как при сохранении.

Имя базы данных определяется подключением MONGO в index.js, а коллекция
внутри этой базы явно задана третьим аргументом модели: posts.
*/
