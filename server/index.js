import express from 'express';
import 'dotenv/config';
import routes from './routes/routes.js';

const app = express();

// укажем middleware для обработки JSON
app.use(express.json());

// middleware для обработки маршрутов
// api - префикс (по желанию можно изменить), routes - объект маршрутов
app.use('/api', routes);

const PORT = process.env.PORT || 4000;

app.listen(PORT, () => {
  console.log(`Server is running on port ${PORT}`);
});

/*
Подробное объяснение index.js

Этот файл — точка входа в сервер: здесь мы создаём приложение Express,
подключаем обработчики запросов и запускаем прослушивание порта.

1. import express from 'express'
   Импортируем Express — библиотеку для создания HTTP-сервера и маршрутов.
   Синтаксис import доступен здесь благодаря "type": "module" в package.json.

2. import 'dotenv/config'
   Загружаем переменные из файла .env в process.env. При обычной настройке
   dotenv ищет .env в текущей рабочей папке, из которой запущен процесс.
   Например, PORT=5000 позволяет задать порт без изменения этого файла.
   Уже заданные переменные окружения по умолчанию не перезаписываются.

3. import routes from './routes/routes.js'
   Подключаем маршрутизатор, который экспортируется из routes.js.
   Название routes мы выбираем при импорте: внутри routes.js этот же объект
   называется router, а передаётся он через export default.

4. const app = express()
   Создаём приложение. Через app настраиваем обработку запросов и запуск сервера.

5. app.use(express.json())
   Подключаем middleware — промежуточный обработчик запроса.
   Он разбирает тело запроса с JSON при подходящем Content-Type
   (обычно application/json) и помещает полученные данные в req.body.
   Например, JSON { "text": "Привет" } станет объектом с полем text.
   Этот обработчик стоит перед маршрутами, чтобы в них уже был доступен req.body.
   Он не предназначен для загрузки файлов или разбора обычных HTML-форм.

6. app.use('/api', routes)
   Подключаем все маршруты из routes.js с общим префиксом /api.
   Поэтому '/' внутри маршрутизатора соответствует адресу /api,
   а '/:id' — адресу вида /api/123. HTTP-метод тоже участвует в выборе маршрута:
   GET /api и POST /api попадут в разные обработчики.

7. const PORT = process.env.PORT || 4000
   Берём порт из окружения. Если значение отсутствует или является пустой
   строкой, используем 4000. Оператор || выбирает запасное значение справа,
   когда значение слева является ложным при преобразовании к boolean.

8. app.listen(PORT, ...)
   Запускаем сервер на выбранном порту. Переданная функция вызывается,
   когда сервер начал слушать, и выводит сообщение в терминал.
   Обратные кавычки и ${PORT} позволяют вставить значение порта в строку.
   При локальном запуске с портом 4000 API доступно по http://localhost:4000/api.

Путь запроса: клиент → приложение → express.json() → маршрутизатор /api
→ подходящий обработчик в routes.js → ответ клиенту.
Подключения к базе данных в этом файле пока нет.
*/
